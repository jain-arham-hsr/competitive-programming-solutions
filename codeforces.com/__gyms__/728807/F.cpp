template <typename T> struct SegTree {
    int n;
    vector<T> tree;

    SegTree(int n, vector<T> &arr) : n(n), tree(4 * n) {
        build(1, 0, n - 1, arr);
    }

    void build(int node, int start, int end, vector<T> &arr) {
        if (start == end) {
            tree[node] = arr[start];
            return;
        }
        int mid = (start + end) / 2;
        build(2 * node, start, mid, arr);
        build(2 * node + 1, mid + 1, end, arr);
        tree[node] = combine(tree[2 * node], tree[2 * node + 1]);
    }

    void update(int node, int start, int end, int idx, T val) {
        if (start == end) {
            tree[node] = val;
            return;
        }
        int mid = (start + end) / 2;
        if (idx <= mid)
            update(2 * node, start, mid, idx, val);
        else
            update(2 * node + 1, mid + 1, end, idx, val);
        tree[node] = combine(tree[2 * node], tree[2 * node + 1]);
    }

    T query(int node, int start, int end, int l, int r) {
        if (r < start || end < l)
            return identity();
        if (l <= start && end <= r)
            return tree[node];
        int mid = (start + end) / 2;
        return combine(query(2 * node, start, mid, l, r),
                       query(2 * node + 1, mid + 1, end, l, r));
    }

    // ── change these for sum / min / max
    // ──────────────────────────────────────
    T combine(T a, T b) { return a & b; }
    T identity() {
        return T(INT_MAX);
    } // 0 for sum, INT_MAX for min, INT_MIN for max

    // ── public interface
    // ───────────────────────────────────────────────────────
    void update(int idx, T val) { update(1, 0, n - 1, idx, val); }
    T query(int l, int r) { return query(1, 0, n - 1, l, r); }
};

int main() {
    ios::sync_with_stdio(false);
    cin.tie(0);

    int T;
    cin >> T;
    while (T--) {
        int n;
        cin >> n;
        vector<int> a(n);
        for (auto &x : a)
            cin >> x;

        int q;
        cin >> q;

        SegTree<int> st(n, a);

        while (q--) {
            int l, k;
            cin >> l >> k;

            l--;
            if (a[l] < k) {
                cout << -1 << " ";
                continue;
            }

            int lo = l - 1, hi = n;
            while (lo < hi - 1) {
                int mid = lo + (hi - lo) / 2;

                if (st.query(l, mid) < k) {
                    hi = mid;
                } else {
                    lo = mid;
                }
            }

            cout << lo + 1 << " ";
        }
        cout << "\n";
    }
    return 0;
}
