int main() {
    ios::sync_with_stdio(false);
    cin.tie(0);

    int T;
    cin >> T;
    while (T--) {
        int n;
        cin >> n;

        vector<pair<int, int>> intervals(n);
        for (int i = 0; i < n; i++) {
            cin >> intervals[i].first >> intervals[i].second;
        }

        ll l = -1, r = 1e9 + 1;
        while (l < r - 1) {
            ll mid = l + (r - l) / 2;

            ll can_reach_left = 0;
            ll can_reach_right = 0;

            bool valid = true;

            for (int i = 0; i < n; i++) {
                can_reach_left -= mid;
                can_reach_right += mid;

                pair<ll, ll> a = {can_reach_left, can_reach_right};
                pair<ll, ll> b = intervals[i];

                if (b.first < a.first)
                    swap(a, b);

                if (a.second < b.first) {
                    valid = false;
                    break;
                }
                can_reach_left = max(a.first, b.first);
                can_reach_right = min(a.second, b.second);
            }

            if (valid) {
                r = mid;
            } else {
                l = mid;
            }
        }

        cout << r << "\n";
    }
    return 0;
}
