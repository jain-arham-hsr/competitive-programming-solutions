int main() {
    ios::sync_with_stdio(false);
    cin.tie(0);

    int T;
    cin >> T;
    while (T--) {
        int n;
        cin >> n;

        vector<int> freq(2e5 + 1);

        vector<vector<int>> inp;
        inp.reserve(n);

        for (int i = 0; i < n; i++) {
            int k;
            cin >> k;
            vector<int> p(k);
            for (int j = 0; j < k; j++) {
                cin >> p[j];
                freq[p[j]]++;
            }
            inp.push_back(p);
        }

        bool ok = false;

        for (int i = 0; i < n; i++) {
            bool flag = true;
            for (auto x : inp[i]) {
                if (freq[x] < 2)
                    flag = false;
            }
            if (flag)
                ok = true;
        }

        cout << (ok ? "YES\n" : "NO\n");
    }
    return 0;
}
