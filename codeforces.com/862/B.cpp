pair<ll, ll> bfs(int n, int src, vector<vector<int>> &adj) {
    ll grp_0_cnt = 0, grp_1_cnt = 0;

    vector<bool> visited(n, false);
    queue<pair<int, bool>> q;
    visited[src] = true;
    q.push({src, 0});

    while (!q.empty()) {
        int u = q.front().first;
        bool grp = q.front().second;
        q.pop();

        if (grp)
            grp_1_cnt++;
        else
            grp_0_cnt++;

        for (int v : adj[u])
            if (!visited[v]) {
                visited[v] = true;
                q.push({v, !grp});
            }
    }

    return {grp_0_cnt, grp_1_cnt};
}

int main() {
    ios::sync_with_stdio(false);
    cin.tie(0);

    int n;
    cin >> n;

    vector<vector<int>> adjList(n + 1);

    for (int i = 0; i < n - 1; i++) {
        int a, b;
        cin >> a >> b;

        adjList[a].push_back(b);
        adjList[b].push_back(a);
    }

    pair<ll, ll> grp_cnts = bfs(n + 1, 1, adjList);

    cout << (grp_cnts.first * grp_cnts.second - n + 1);

    return 0;
}
