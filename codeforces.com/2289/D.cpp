template <typename It> long long count_inversions(It first, It last) {
    using T = typename iterator_traits<It>::value_type;
    vector<T> a(first, last);
    int n = a.size();
    vector<T> tmp(n);
    long long inv = 0;
    for (int w = 1; w < n; w *= 2) {
        for (int l = 0; l < n; l += 2 * w) {
            int m = min(l + w, n), r = min(l + 2 * w, n);
            int i = l, j = m, k = l;
            while (i < m && j < r) {
                if (a[j] < a[i]) {
                    inv += m - i;
                    tmp[k++] = a[j++];
                } else
                    tmp[k++] = a[i++];
            }
            while (i < m)
                tmp[k++] = a[i++];
            while (j < r)
                tmp[k++] = a[j++];
        }
        swap(a, tmp);
    }
    return inv;
}

int main() {
    ios::sync_with_stdio(false);
    cin.tie(0);

    int T;
    cin >> T;
    while (T--) {
        int n;
        cin >> n;
        vector<ll> nums(n);
        for (auto &x : nums)
            cin >> x;

        vector<ll> prefSum(n + 1);
        partial_sum(all(nums), prefSum.begin() + 1);

        bool valid = true;
        for (int i = 1; i <= n; i++) {
            if (prefSum[i] < 0) {
                valid = false;
                break;
            }
        }

        if (!valid)
            cout << -1 << "\n";
        else
            cout << count_inversions(prefSum.begin() + 1, prefSum.end())
                 << "\n";
    }
    return 0;
}
