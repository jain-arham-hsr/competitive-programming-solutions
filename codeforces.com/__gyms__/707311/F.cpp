int ringInd(int n, int x, int y) {
    int l = x, r = n - x + 1, t = y, b = n - y + 1;
    return min(l, min(r, min(t, b)));
}

int main() {
    ios::sync_with_stdio(false);
    cin.tie(0);

    int T;
    cin >> T;
    while (T--) {
        int n, x1, y1, x2, y2;
        cin >> n >> x1 >> y1 >> x2 >> y2;

        cout << abs(ringInd(n, x1, y1) - ringInd(n, x2, y2)) << "\n";
    }
    return 0;
}
