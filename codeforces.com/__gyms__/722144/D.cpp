void setVal(int i, char val, int &n, int &m, string &s, char &lastChar,
            int &consecCnt) {
    s[i] = val;
    if (lastChar != val)
        consecCnt = 0;
    consecCnt++;
    lastChar = val;
    if (val == '0')
        n--;
    else
        m--;
}

int main() {
    ios::sync_with_stdio(false);
    cin.tie(0);

    int n, m;
    cin >> n >> m;

    string s(n + m, 'p');

    bool ok = true;

    int consecCnt = 0;
    char lastChar = ' ';
    for (int i = 0; i < s.size(); i++) {
        watch(n, m);
        if (n >= m && n > 0) {
            if (lastChar != '0') {
                setVal(i, '0', n, m, s, lastChar, consecCnt);
            } else if (m > 0) {
                setVal(i, '1', n, m, s, lastChar, consecCnt);
            } else {
                ok = false;
                break;
            }
        } else if (m >= n && m > 0) {
            if (lastChar != '1' || consecCnt <= 1) {
                setVal(i, '1', n, m, s, lastChar, consecCnt);
            } else if (n > 0) {
                setVal(i, '0', n, m, s, lastChar, consecCnt);
            } else {
                ok = false;
                break;
            }
        } else {
            ok = false;
            break;
        }
        watch(s);
    }

    if (!ok)
        cout << "-1\n";
    else
        cout << s << "\n";

    return 0;
}
